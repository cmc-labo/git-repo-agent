export function findLanguage(code: string | null | undefined): Language | undefined {
  if (!code) return undefined;
  return LANGUAGES.find((l) => l.code.toLowerCase() === code.toLowerCase());
}

/** ブラウザの言語設定 (navigator.languages) に合う候補を返す */
export function suggestLanguages(browser: readonly string[]): Language[] {
  const out: Language[] = [];
  const push = (l?: Language) => l && !out.includes(l) && out.push(l);
  for (const b of browser) {
    push(findLanguage(b));
    const base = b.split("-")[0].toLowerCase();
    if (base === "zh") push(findLanguage(/TW|HK|MO|Hant/i.test(b) ? "zh-TW" : "zh-CN"));
    else if (base === "pt") push(findLanguage(/PT/i.test(b) ? "pt-PT" : "pt-BR"));
    else if (base === "no" || base === "nn") push(findLanguage("nb"));
    else if (base === "iw") push(findLanguage("he"));
    else if (base === "tl") push(findLanguage("fil"));
    else push(findLanguage(base));
  }
  return out.slice(0, 4);
}
